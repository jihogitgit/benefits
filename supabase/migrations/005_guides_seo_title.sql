-- 화면의 h1과 <title>을 같은 문장으로 쓰고 있었다. 가이드 제목은 전부 "통념 → 반전 숫자"
-- 구조인데(예: "프리랜서 출산급여 150만원, 고용보험에 들어 있으면 최대 660만원입니다"),
-- 한글 검색결과는 대략 30자 전후에서 잘려 클릭 이유인 반전이 예외 없이 절단선 뒤로 간다.
-- 발행 10편을 실제로 재어 보니 32~49자였고, 브랜드 접미사 ' | 내몫'까지 붙어 37~54자다.
--
--   국가장학금에서 떨어졌다면, 소득을 아예 안 보는 장학금이 2…   ← 255개가 잘린다
--   프리랜서 출산급여 150만원, 고용보험에 들어 있으면 최대 …    ← 660만원이 잘린다
--   폐업 지원금은 순서가 금액을 바꿉니다, 지자체 철거비를 먼저…  ← 600만원이 막힌다
--
-- 화면 제목은 좋은 문장이라 그대로 두고 검색용만 따로 둔다. title 하나를 짧게 고치면
-- 페이지를 여는 사람이 보는 문장까지 같이 나빠진다.
--
-- nullable이다. 채우지 않은 가이드는 null이고 읽는 쪽에서 title로 떨어진다. 기존 행을
-- title로 채우지 않는 이유가 여기 있다 — 채우면 "검색용을 따로 쓰지 않았음"과 "검색용을
-- 본문 제목과 같게 두기로 했음"을 구분할 수 없다. 004_guides_updated_at과 같은 판단이다.
