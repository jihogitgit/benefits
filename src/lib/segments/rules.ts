import type { Segment } from '@/types/database'

export interface SegmentTextInput {
  title: string | null
  target_text: string | null
  summary: string | null
}

export interface SegmentCondInput {
  age_min: number | null
  age_max: number | null
  life_stages: string[]
  occupations: string[]
  household_types: string[]
}

const YOUTH_KW = /청년|대학생|취업준비|신혼부부/

/**
 * 출산·육아 낱말.
 *
 * 아래 수치는 전부 **benefits 전체 10,968건**(status 무관) 기준이다. segments는 마감된 행에도
 * 저장되므로 open만 세면 감사할 때 어긋난다.
 *
 * ## 뺀 것
 *
 * `출생`. 한글에는 낱말 경계가 없어 이 낱말이 **나이와 출신지를 적는 표현**에 통째로 걸렸다.
 * 안내문은 나이 상한을 "1954년 12월 31일 이전 출생"으로, 출신지 요건을 "고흥군에서 출생한
 * 자"로 쓴다. 그래서 노인 장수수당·어르신 폐렴구균·보훈 진료비·귀향 정착장려금·다문화·
 * 북한이탈주민 지원이 전부 출산·육아로 들어왔다 — `출생`이 유일하게 걸리는 낱말이고 조건
 * 코드 근거도 없는 110건 중, 실제 출산·육아는 **10건**이었다.
 *
 * ## 대신 넣은 것 — 회수
 *
 * `출생`을 빼기만 하면 그 10건이 함께 사라진다. 그래서 **더 좁은 낱말로 바꿔 넣었다** —
 * 위 110건 중 **10건이 새 낱말로 남고 100건이 빠진다.** 빠지는 100건이 노인 장수수당·
 * 보훈·귀향·다문화 쪽이다.
 *
 * - `신생아·출생아·미숙아·태아·둘째아·셋째아·출생신고` — 출산 자체의 신호. `태아`가
 *   `다태아`·`쌍태아`·`단태아`를 포함하므로 `다태아`를 따로 두지 않는다.
 * - `어린이` — 어린이 예방접종·급식관리·교통비를 되찾는다. `어린이집`을 포함하므로(매치
 *   뒷글자 475개 중 273개가 `집`) 그것을 따로 두지 않는다.
 * - `(?<!모)두 ?자녀` — 안내문이 `다자녀`가 아니라 "두 자녀"로 쓴다. 앞말 가드는 `모두 자녀`
 *   ("부모가 모두 자녀의 출생일 기준")를 막는다. 걸리는 네 행은 `양육`·`출산`으로 독립 근거가
 *   있어 지금 오분류는 없지만, 이 파일이 고치는 것과 같은 종류라 미리 막는다.
 * - `환아` — 아토피·선천성 질환 아동 의료비. 성인 환자에는 쓰지 않는 말이다.
 * - `자녀교육` — 한부모·저소득 자녀교육비, 꿈나래통장.
 *
 * 세는 방법이 셋이라 전부 적어 둔다. 집합을 헷갈려 쓰다가 검수에서 세 번 걸렸다 — 숫자를
 * 인용할 때 어느 집합인지 함께 적지 않으면 다음 사람이 재현하지 못한다.
 *
 *   `출생`만 걸리고 코드 근거도 없는 행 ... 110건 (유지 10 / 빠짐 100)  ← 위 문단의 셈
 *   `출생`만 걸리는 행, 코드 무관 ......... 139건 (유지 39 / 빠짐 100)
 *   드라이런에서 출산·육아를 잃는 행 ...... 109건 (출생 단독 100 / 아래 `보육` 가드 9)
 *
 * 마지막 것은 앞의 둘과 다른 집합이다. 9건은 창업 사업이고 `출생`과 무관하다.
 *
 * `어린이`의 오탐은 셋이다 — 두루누리(어린이 통학버스 **기사**), 슬레이트 처리(어린이**시설**
 * 소유자), 달성 장학금(초록우산 어린이**재단** 선발). 대상이 아니라 직업·시설·단체 이름에
 * 걸린 것이다. 이 셋은 `어린이`를 가졌고 다른 출산·육아 낱말이 없는 행을 읽어 찾았고,
 * 그중 달성 장학금은 조건 코드로 **이 변경과 무관하게 이미** 출산·육아였다 — 경로는
 * `life_stages`의 `elementary`다. `age_max`는 18이라 CHILD_AGE_MAX(12)에 걸리지 않는다.
 *
 * ## 대신 넣은 것 — 회수가 아닌 결정
 *
 * `다둥이`는 위 110건을 **하나도 되찾지 않는다**(세 집합 어느 것으로 세도 0건이다). 대신 **새로 48건을 출산·육아에 넣는다**
 * (그중 47건은 제목에 감면·할인·요금·료가 있는 지자체 요금감면이고, 나머지 하나는
 * 서울시민대학이다 — 주차 19·체육 21·문화 4·숙박 2·기타 2). "다둥이행복카드 소지자"가 국가유공자·기초생활수급자·장애인·65세 이상과
 * 나란히 나열된 목록형 사업이다.
 *
 * 넣기로 한 이유는 수혜자가 **다자녀 가정의 부모와 자녀 본인**이기 때문이다. 아래에서 `자녀`를
 * 기각한 것과 여기가 갈리는 지점이 그것이다 — `자녀`가 걸리는 6·25자녀수당은 수혜자가
 * 유공자의 자녀이고, 손자녀 돌봄은 조부모이고, 장학금은 학생이다. 다자녀 카드 감면은 아이를
 * 둘 이상 키우는 일 때문에 받는 돈이다.
 *
 * 다만 이 48건은 세그먼트 성격을 바꾼다. 출산·육아가 출산·양육 사업 위주였는데 요금감면이
 * 한 덩어리로 들어온다. 아래 `소기업`의 근로자 22건과 같은 수준의 **알려진 변화**로 적어 둔다.
 *
 * ## 넣지 않은 것
 *
 * `자녀`는 단독 443건인데 장학금·보훈수당(6·25자녀수당)·손자녀 돌봄이 섞여 오탐이 크다.
 * `아기`는 "‘아기유니콘 200 육성"(창업 보증)과 "소아기 및 청소년기"에, `산전`은
 * "비슬산전기차"(문화시설 감면)에 걸려 넣지 않았다.
 *
 * ## 가드
 *
 * `보육`은 **창업 인큐베이션**을 뜻할 때가 있다. `보육센터`·`보육 프로그램`을 가진 8건은
 * 전부 창업이고(스마트팜 청년창업 보육센터, 장애인기업 창업보육센터, 창업존 보육프로그램 …)
 * 육아 쪽에는 하나도 없다. 앞말 `창업`과 뒷말 `센터·프로그램` 둘을 다 막아야 한다 —
 * `창업보육지원`은 앞말로, `창업 보육센터`(공백)는 뒷말로만 걸린다.
 *
 * 남는 오탐 둘은 기록해 둔다. 팁스의 "先투자/보육/추천"과 소상공인 희망센터의 "(보육지원)"은
 * 앞말이 구분자이고 뒷말도 센터·프로그램이 아니라 이 가드를 통과한다. 규칙을 더 붙이면
 * 읽을 수 없어지는 지점이라 두 건을 남기는 쪽을 골랐다.
 */
const PARENTING_KW =
  /임산부|임신|출산|산모|산후|영유아|영아|유아|아동|양육|육아|(?<!창업)보육(?!\s*(?:센터|프로그램))|유치원|다자녀|첫만남|부모급여|아이돌봄|신생아|출생아|출생신고|미숙아|태아|둘째아|셋째아|어린이|(?<!모)두 ?자녀|다둥이|환아|자녀교육/

/**
 * 소상공인 낱말.
 *
 * `상인`에 앞말 가드를 달았다. 가드가 없을 때 이 낱말은 **`이상인`에 파묻혀** 걸렸다 —
 * "본인부담금액 20,000원 이상인 경우", "만 65세 이상인 자" 같은 문장 전부다. `상인`이 유일한
 * 근거인 302건 중 297건이 그것이었고, 제주 소상공인 목록 맨 앞에 "4.3생존희생자·유족·며느리
 * 진료비 지원"이 오게 된 원인이다. `대상인`("지원 대상인 경우")도 같다.
 *
 * 앞말을 전부 막지 않고 `이`와 `대`만 막는다. `[가-힣]`을 통째로 막으면 시장상인·청년상인·
 * 소상인처럼 낱말 안에 있는 것이 정상인 쪽까지 잃는다. 가드를 통과하는 `상인` 63건의 앞말은
 * 장(시장상인)·소(소상인)·년(청년상인)·권·점·래(가축거래상인)뿐이고, `이`나 `대`로 끝나는
 * 낱말 뒤에 정상적으로 `상인`이 오는 경우는 한 건도 없었다.
 *
 * `음식점`을 넣었다. 음식점 시설개선·모범음식점·외식업소 지원이 소상공인 사업인데 안내문에
 * 다른 낱말이 없어 빠져 있었다(단독 15건). `일반음식점`·`휴게음식점`·`독립음식점`은 모두
 * 같은 뜻의 복합어다.
 *
 * `업소`는 넣지 않았다. `창업소`("28청춘창업소")·`직업소`("직업소유자")·`사업소`("근로사업
 * 소득")에 파묻혀, 고치려는 것과 같은 종류의 버그를 새로 만든다.
 *
 * 그 대가로 `HACCP 위생안전시설 개선 자금 지원`은 알려진 누락으로 남는다. 안내문이 대상을
 * "소규모 작업장", "매출액 100억원 이상인 업소 제외"로만 쓰고 소상공인·사업자·점포·음식점을
 * 한 번도 쓰지 않는다. 이 한 건을 잡으려고 `업소`를 넣으면 위 세 낱말에 파묻힌 오탐 수십
 * 건이 따라온다 — 한 건을 남기는 쪽이 싸다.
 *
 * `소기업`은 `중소기업`에도 걸리고, 그대로 둔다. 소상공인은 소기업의 부분집합이라(소상공인
 * 기본법) 중소기업 대상 사업은 소상공인도 신청할 수 있다 — 넓게 잡는 쪽이 독자에게 맞다.
 * 단독 근거 179건 중 178건이 중소기업이므로 이 판단을 바꾸면 세그먼트가 그만큼 줄어든다.
 * 다만 그중 22건은 수혜자가 사업주가 아니라 **직원·구직 청년**이어서(청년 일자리 매치업,
 * 청년내일근속지원, 중소기업 재직자 분할상환 …) 세그먼트를 희석한다. 알려진 한계로 남긴다.
 *
 * `강소기업`(8건, 글로벌 강소기업 1,000+ 프로젝트 등)도 걸린다. 강소기업은 소기업의
 * 부분집합이 아니어서 위 논거가 닿지 않는다 — 이쪽은 근거 없이 넓게 잡은 것으로 기록한다.
 */
const SMALL_BIZ_KW = /소상공인|자영업|소기업|점포|창업|사업자|가게|(?<![이대])상인|전통시장|폐업|음식점/

/**
 * 이 생애주기 코드가 있으면 출산·육아로 본다. 코드는 원천(보조금24)이 준 값이다.
 *
 * 원천이 생애주기를 넓게 적어 둔 사업은 텍스트가 육아와 무관해도 여기로 들어온다. 실제로
 * `스마트팜 청년창업 보육센터`가 pre_parent·pregnancy·birth를 달고 있어 낱말 가드를 통과한
 * 뒤에도 출산·육아로 남는다.
 *
 * 그렇다고 코드를 덜 믿게 바꾸지 않았다. 규모를 재 보니 **생애주기 코드로** 붙는 1,701건 중
 * 생애주기를 네 개 이상 나열한 것은 7건, 그중 코드가 유일한 근거인 것은 2건이다 — "전부
 * 나열해서 무의미해진" 경우가 드물어 임계값을 걸 근거가 없다. household_types를 믿지 않는
 * 것과는 사정이 다르다(그쪽은 복지 서비스 대부분이 여러 가구 유형을 함께 나열한다).
 *
 * 아래 CHILD_AGE_MAX 경로를 더하면 코드로 parenting이 붙는 행은 1,938건이다.
 */
const PARENTING_STAGES = new Set(['pre_parent', 'pregnancy', 'birth', 'elementary'])
// 이 나이 이하를 대상으로 하면 보호자가 신청하는 아동 지원으로 본다
const CHILD_AGE_MAX = 12

/** 조건 코드와 텍스트 키워드로 세그먼트를 부여한다. 어디에도 해당하지 않으면 ['other']. */
export function tagSegments(text: SegmentTextInput, cond: SegmentCondInput): Segment[] {
  const hay = `${text.title ?? ''} ${text.target_text ?? ''} ${text.summary ?? ''}`
  const out: Segment[] = []

  const youthByAge = cond.age_min !== null && cond.age_max !== null && cond.age_min >= 18 && cond.age_max <= 39
  if (youthByAge || YOUTH_KW.test(hay)) out.push('youth')

  // 한부모·다자녀 같은 가구 유형만으로는 판정하지 않는다. 복지 서비스 대부분이 여러 가구 유형을 함께 나열해 오탐이 크다.
  const childByAge = cond.age_max !== null && cond.age_max <= CHILD_AGE_MAX
  const parentingByCode = cond.life_stages.some((s) => PARENTING_STAGES.has(s)) || childByAge
  if (parentingByCode || PARENTING_KW.test(hay)) out.push('parenting')

  if (cond.occupations.includes('small_biz') || SMALL_BIZ_KW.test(hay)) out.push('small_biz')

  return out.length ? out : ['other']
}
